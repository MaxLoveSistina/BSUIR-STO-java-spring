package com.sto.autoservice.core.entity;

/**
 * Роли пользователей (RBAC).
 */
public enum Role {
    /**
     * Клиент: выбирает мастера, услуги, материалы и сроки, оформляет заказы.
     */
    ROLE_CLIENT,

    /**
     * Мастер: ведёт собственный каталог услуг, обрабатывает заказы, видит своих клиентов.
     */
    ROLE_MASTER
}
